import "@/app/globals.css";

import { SiteHeader } from "@duyet/components/SiteHeader";
import { SiteFooter } from "@duyet/components/SiteFooter";
import {
  duyetFaviconHeadLinks,
  duyetFontHeadLinks,
  THEME_BOOT_SCRIPT,
  ExploreApps,
} from "@duyet/components";
import { homelabConfig } from "@duyet/config";
import { ogHeadLinks, ogMetaFromConfig } from "@duyet/config/og";
import {
  createRootRoute,
  HeadContent,
  Outlet,
  Scripts,
} from "@tanstack/react-router";
import ErrorPage from "@/app/error";
import NotFoundPage from "@/app/not-found";
import ThemeProvider from "@duyet/components/ThemeProvider";

const HOMELAB_URL =
  homelabConfig.metadata.openGraph?.url ?? "https://homelab.duyet.net";

/**
 * The config supplies the image URL (`/og.png`, generated by
 * `pnpm run og:card` from `scripts/generate-og.ts`) and the real `@_duyet`
 * handle. Only the title and description are overridden, so the OG copy
 * matches what the page actually renders.
 */

export const Route = createRootRoute({
  head: () => ({
    meta: [
      { charSet: "utf-8" },
      { name: "viewport", content: "width=device-width, initial-scale=1.0" },
      { name: "robots", content: "follow, index" },
      { title: homelabConfig.metadata.title },
      { name: "description", content: homelabConfig.metadata.description },
      // The config supplies url/site_name/locale/type/image and twitter:card;
      // title and description are overridden so the OG copy matches what the
      // page actually renders.
      ...ogMetaFromConfig(homelabConfig.metadata, {
        title: homelabConfig.metadata.title,
        description: homelabConfig.metadata.description,
      }),
    ],
    links: [
      ...duyetFontHeadLinks(),
      ...ogHeadLinks({
        url: HOMELAB_URL,
        manifest: homelabConfig.metadata.manifest,
      }),
      ...duyetFaviconHeadLinks(),
    ],
  }),
  errorComponent: ({ error, reset }) => (
    <ErrorPage
      error={error instanceof Error ? error : new Error(String(error))}
      reset={reset}
    />
  ),
  notFoundComponent: () => <NotFoundPage />,
  component: RootComponent,
});

function RootComponent() {
  return (
    <html lang="en" className="dark" suppressHydrationWarning>
      <head>
        <script dangerouslySetInnerHTML={{ __html: THEME_BOOT_SCRIPT }} />
        <HeadContent />
      </head>
      <body>
        <ThemeProvider forcedTheme="dark" defaultTheme="dark" enableSystem={false}>
          <div className="relative flex min-h-screen flex-col justify-between overflow-x-hidden bg-background text-foreground subpixel-antialiased">
            <SiteHeader currentApp="homelab" hideThemeToggle />
            <main className="relative z-10 flex-grow">
              <Outlet />
            </main>
            <ExploreApps currentApp="homelab" />
            <SiteFooter />
          </div>
        </ThemeProvider>
        <Scripts />
      </body>
    </html>
  );
}
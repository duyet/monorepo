import type { DataSourceAdapter, MergeStats, Model } from "./types";

/**
 * Escape a string for embedding in a TypeScript single-quoted literal.
 */
export function singleQuote(s: string): string {
  if (s == null) return "";
  return s
    .replace(/\\/g, "\\\\")
    .replace(/'/g, "\\'")
    .replace(/\n/g, "\\n")
    .replace(/\r/g, "\\r");
}

/**
 * Generate the full content of lib/data.ts from merged model data.
 */
export function generateDataTs(
  models: Model[],
  sources: DataSourceAdapter[],
  syncedAt: string,
  stats: MergeStats
): string {
  const syncDate = /^\d{4}-\d{2}-\d{2}/.test(syncedAt)
    ? syncedAt.slice(0, 10)
    : syncedAt;
  // Build merge stats line: "771 curated + 3156 epoch - 1 duplicates = 3926 total"
  const statsLine = Object.entries(stats.sources)
    .map(([name, count]) => `${count} ${name}`)
    .join(" + ")
    .concat(` - ${stats.duplicates} duplicates = ${stats.total} total`);

  // Build data sources block for the header comment
  const sourcesBlock = sources
    .map((s) => {
      const urlLines = s.urls.map((url) => ` *   ${url}`).join("\n");
      return ` *   ${s.label}:\n${urlLines}`;
    })
    .join("\n");

  // Build each model entry
  const modelEntries = models
    .map((m) => {
      const lines: string[] = [];
      lines.push(`    name: '${singleQuote(m.name)}'`);
      lines.push(`    date: '${singleQuote(m.date)}'`);
      lines.push(`    org: '${singleQuote(m.org)}'`);
      lines.push(
        `    params: ${m.params === null ? "null" : `'${singleQuote(m.params)}'`}`
      );
      lines.push(`    type: '${m.type}'`);
      lines.push(`    license: '${m.license}'`);
      lines.push(`    desc: '${singleQuote(m.desc)}'`);
      if (m.source != null)
        lines.push(`    source: '${singleQuote(m.source)}'`);
      if (m.domain != null)
        lines.push(`    domain: '${singleQuote(m.domain)}'`);
      if (m.link != null)
        lines.push(`    link: '${singleQuote(m.link)}'`);
      if (m.trainingCompute != null)
        lines.push(`    trainingCompute: '${singleQuote(m.trainingCompute)}'`);
      if (m.trainingHardware != null)
        lines.push(
          `    trainingHardware: '${singleQuote(m.trainingHardware)}'`
        );
      if (m.trainingDataset != null)
        lines.push(`    trainingDataset: '${singleQuote(m.trainingDataset)}'`);
      if (m.authors != null)
        lines.push(`    authors: '${singleQuote(m.authors)}'`);
      return `  {\n${lines.join(",\n")},\n  }`;
    });

  // Emit the array as chunks of `Model[]` rather than one literal.
  //
  // A single literal with 4,000+ distinct object literal types makes TypeScript
  // attempt the union of all of them and give up with
  // `TS2590: Expression produces a union type that is too complex to represent`
  // — which is why this file used to carry `// @ts-nocheck`. That exempted the
  // app's entire dataset, 4,307 rows, from type-checking: the one file most in
  // need of it was the one exempt from it.
  //
  // Chunking collapses the union to `Model`, so the generated file checks clean
  // with no pragma. Verified byte-identical at runtime: the JSON of the imported
  // `models` array is unchanged, and 16 value-importers are unaffected because
  // the exported type was and still is `Model[]`.
  //
  // `scripts/chunk-data-ts.ts` applied the same transformation to the committed
  // file without needing a network sync.
  const CHUNK_SIZE = 250;
  const chunkBlocks: string[] = [];
  for (let start = 0; start < modelEntries.length; start += CHUNK_SIZE) {
    const slice = modelEntries.slice(start, start + CHUNK_SIZE);
    chunkBlocks.push(
      `const c${chunkBlocks.length}: Model[] = [\n${slice
        .map((entry) => `  ${entry}`)
        .join(",\n")},\n];`
    );
  }

  const modelsDeclaration = [
    "// Machine-generated by scripts/sync-data.ts — do not edit by hand.",
    "//",
    "// The array is emitted as chunks of `Model[]` rather than one literal. A",
    "// single literal with 4,000+ distinct object literal types makes",
    "// TypeScript give up with TS2590 (\"union type that is too complex to",
    "// represent\"), which is why this file used to need `@ts-nocheck` — i.e.",
    "// the app's entire dataset was the one file exempt from type-checking.",
    "// Chunking collapses the union to `Model`, so the file checks clean.",
    "",
    ...chunkBlocks,
    "",
    `export const models: Model[] = [${chunkBlocks
      .map((_, index) => `...c${index}`)
      .join(", ")}].flat();`,
  ].join("\n");

  return `/**
 * LLM Timeline Data
 *
 * ============================================================================
 * LLM UPDATE INSTRUCTIONS
 * ============================================================================
 * To add a new model, append an object to the \`models\` array with:
 *   - name: Model name (e.g., "GPT-4o")
 *   - date: Release date as YYYY-MM-DD
 *   - org: Organization (e.g., "OpenAI", "Anthropic", "Google")
 * LLM Timeline Data
 *
 * ============================================================================
 * LLM UPDATE INSTRUCTIONS
 * ============================================================================
 * To add a new model, append an object to the \`models\` array with:
 *   - name: Model name (e.g., "GPT-4o")
 *   - date: Release date as YYYY-MM-DD
 *   - org: Organization (e.g., "OpenAI", "Anthropic", "Google")
 *   - params: Parameter count as string or null (e.g., "175B", "1.8T (MoE)")
 *   - type: "model" for regular models, "milestone" for key events
 *   - license: "open" | "closed" | "partial"
 *   - desc: Brief description
 *   - source: data source origin (optional, e.g. 'curated', 'epoch')
 *
 * To update existing data, find the model by name and modify fields.
 *
 * Data sources:
${sourcesBlock}
 *
 * Merge stats: ${statsLine}
 * Last synced: ${syncedAt}
 * ============================================================================
 */

export interface Model {
  name: string
  date: string // YYYY-MM-DD
  org: string
  params: string | null // e.g., "175B", "1.8T (MoE)"
  type: 'model' | 'milestone'
  license: 'open' | 'closed' | 'partial'
  desc: string
  source?: string
  domain?: string
  link?: string
  trainingCompute?: string
  trainingHardware?: string
  trainingDataset?: string
  authors?: string
}

${modelsDeclaration}

export const organizations: string[] = Array.from(new Set(models.map((m) => m.org))).sort()
export const domains: string[] = Array.from(
  new Set(
    models
      .filter(m => m.domain)
      .flatMap(m => m.domain!.split(',').map(d => d.trim()))
  )
).sort()
export const years: number[] = Array.from(new Set(models.map((m) => new Date(m.date).getFullYear()))).sort(
  (a, b) => b - a,
)
export const lastSynced = '${singleQuote(syncDate)}'
export const syncedAt = '${singleQuote(syncedAt)}'
`;
}
